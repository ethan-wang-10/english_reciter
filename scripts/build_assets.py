"""Build the classic application script and content-addressed HTML asset URLs."""

import argparse
import hashlib
import json
import os
from html.parser import HTMLParser
from html import unescape
from pathlib import Path
import re
import tempfile
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit


ROOT = Path(__file__).resolve().parent.parent
APP_PARTS = (
    "core", "account", "leaderboard", "review-input", "api", "session",
    "learning", "wordbank", "bootstrap",
)
ASSET_SUFFIXES = {".js", ".css", ".svg", ".png", ".jpg", ".jpeg", ".webp", ".ico", ".woff", ".woff2"}
TEXT_ASSET_SUFFIXES = {".js", ".css", ".svg"}
FINGERPRINT = re.compile(r"\.[0-9a-f]{16}(?=\.[^.]+$)")
URL_ATTRIBUTE = re.compile(
    r"(?P<prefix>\b(?:src|href)\s*=\s*)(?P<quote>[\"'])(?P<url>.*?)(?P=quote)",
    re.IGNORECASE | re.DOTALL,
)


def application_bundle(root):
    chunks = ["// Generated by scripts/build_assets.py. Edit static/js/app/ sources.\n"]
    for name in APP_PARTS:
        source = root / "static" / "js" / "app" / (name + ".js")
        chunks.append("\n// Source: static/js/app/" + name + ".js\n")
        chunks.append(source.read_text(encoding="utf-8").rstrip() + "\n")
    return "".join(chunks).encode("utf-8")


class AssetHtml(HTMLParser):
    """Use parsed start tags to update URL tokens without reformatting the page."""

    def __init__(self, root, source, bundle):
        super().__init__(convert_charrefs=False)
        self.root = root.resolve()
        self.source = source
        self.bundle = bundle
        self.assets = {}
        self.fingerprinted = {}
        self.edits = []
        self.line_offsets = [0]
        for line in source.splitlines(keepends=True):
            self.line_offsets.append(self.line_offsets[-1] + len(line))

    def handle_starttag(self, tag, attrs):
        targets = {value for name, value in attrs if name in ("src", "href") and value}
        raw = self.get_starttag_text()
        line, column = self.getpos()
        offset = self.line_offsets[line - 1] + column
        for match in URL_ATTRIBUTE.finditer(raw):
            original = unescape(match.group("url"))
            if original not in targets:
                continue
            parsed = urlsplit(original)
            if parsed.scheme or parsed.netloc or not parsed.path.startswith("/static/"):
                continue
            source_path = parsed.path
            if source_path.startswith("/static/assets/"):
                source_path = "/static/" + FINGERPRINT.sub("", source_path[len("/static/assets/"):])
            asset = (self.root / source_path.lstrip("/")).resolve()
            if not asset.is_relative_to(self.root / "static"):
                raise ValueError("Asset path escapes static directory: " + parsed.path)
            if asset.suffix.lower() not in ASSET_SUFFIXES:
                continue
            if source_path == "/static/js/app.js":
                content = self.bundle
            elif asset.suffix.lower() in TEXT_ASSET_SUFFIXES:
                content = asset.read_text(encoding="utf-8").encode("utf-8")
            else:
                content = asset.read_bytes()
            digest = hashlib.sha256(content).hexdigest()
            query = [(key, value) for key, value in parse_qsl(parsed.query, keep_blank_values=True) if key != "v"]
            relative = Path(source_path[len("/static/"):])
            fingerprinted = relative.with_name(relative.stem + "." + digest[:16] + relative.suffix)
            public_path = "/static/assets/" + fingerprinted.as_posix()
            versioned = urlunsplit(("", "", public_path, urlencode(query), parsed.fragment))
            self.assets[source_path] = {"sha256": digest, "bytes": len(content), "url": versioned}
            self.fingerprinted[self.root / "static" / "assets" / fingerprinted] = content
            quote = match.group("quote")
            escaped = versioned.replace("&", "&amp;").replace(quote, "&quot;" if quote == '"' else "&#x27;")
            self.edits.append((offset + match.start("url"), offset + match.end("url"), escaped))

    handle_startendtag = handle_starttag

    def render(self):
        result = self.source
        for start, end, replacement in reversed(self.edits):
            result = result[:start] + replacement + result[end:]
        return result


def expected_outputs(root):
    root = Path(root).resolve()
    bundle = application_bundle(root)
    source = (root / "static" / "index.html").read_text(encoding="utf-8")
    parser = AssetHtml(root, source, bundle)
    parser.feed(source)
    parser.close()
    manifest = json.dumps({"assets": parser.assets}, ensure_ascii=True, indent=2, sort_keys=True) + "\n"
    return {
        **parser.fingerprinted,
        root / "static" / "js" / "app.js": bundle,
        root / "static" / "asset-manifest.json": manifest.encode("utf-8"),
        root / "static" / "index.html": parser.render().encode("utf-8"),
    }


def build(root=ROOT, check=False):
    outputs = expected_outputs(root)
    changed = [path for path, content in outputs.items() if not path.exists() or path.read_bytes() != content]
    if check:
        return changed
    for path in changed:
        content = outputs[path]
        missing_parents = []
        parent = path.parent
        while not parent.exists():
            missing_parents.append(parent)
            parent = parent.parent
        path.parent.mkdir(parents=True, exist_ok=True)
        for parent in missing_parents:
            parent.chmod(0o755)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(content)
            temporary.chmod(0o644)
            os.replace(temporary, path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when generated assets need rebuilding; write nothing")
    args = parser.parse_args()
    changed = build(check=args.check)
    if args.check and changed:
        print("Stale assets: " + ", ".join(str(path.relative_to(ROOT)) for path in changed))
        return 1
    print("Assets are current" if not changed else "Built " + str(len(changed)) + " asset outputs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
